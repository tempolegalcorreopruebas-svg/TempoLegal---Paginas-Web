import assert from 'node:assert/strict';
import {calcularMultas,parametrosMultas} from './multas-engine.mjs';
import {calcularDelegado,parametrosDelegado} from './delegado-engine.mjs';
import {calcularDiagnostico,respuestasDiagnosticoDesdeIndices,parametrosDiagnostico} from './diagnostico-engine.mjs';
let checks=0;
const eq=(a,b)=>{assert.deepEqual(a,b);checks++};
const entradasMultas={sector:'salud',persona:'juridica',trab:'b',cli:'c',titulares:'b',categorias:'c',vdn:250000,cumple:[]};
const ma=calcularMultas(entradasMultas);
assert.ok(Number.isFinite(ma.total.prob) && ma.score===0);checks++;
eq(ma,calcularMultas(entradasMultas));
const mb=calcularMultas({...entradasMultas,cumple:parametrosMultas.DUTIES.map(x=>x.id)});
assert.equal(mb.score,100);checks++;
assert.ok(mb.total.prob<=ma.total.prob);checks++;
const mod=calcularMultas(entradasMultas,{modo:'detalle'});
assert.equal(mod.total.prob,ma.total.prob);checks++;
const delInput={tit:{s:1},cam:new Set(['ident']),fre:{s:1},per:{s:1},alc:{s:1},sec:new Set([]),dir:new Set([]),ya:'no'};
const da=calcularDelegado(delInput);
assert.equal(da.evaluacion.corresponde,false);checks++;
assert.equal(da.evaluacion.tier,'rev');checks++;
const db=calcularDelegado({...delInput,sec:new Set(['sal'])});
assert.equal(db.evaluacion.corresponde,true);checks++;
assert.equal(db.evaluacion.tier,'si');checks++;
const dc=calcularDelegado({...delInput,ya:'si'});
assert.equal(dc.evaluacion.tier,'ok');checks++;
const empty=calcularDiagnostico({});
assert.equal(empty.completo,false);checks++;
assert.ok(empty.faltantes.includes('tam'));checks++;
const answer = respuestasDiagnosticoDesdeIndices({tam:0,fact:1,sens:0,disp:0,contratos:1,gestion:0});
const diag=calcularDiagnostico(answer);
assert.equal(diag.completo,true);checks++;
assert.ok(diag.montos.lista.length>=0);checks++;
const answerBio=respuestasDiagnosticoDesdeIndices({tam:1,fact:2,sens:0,disp:2,dpd:2,contratos:2,gestion:0});
const diagBio=calcularDiagnostico(answerBio);
assert.equal(diagBio.completo,true);checks++;
assert.equal(diagBio.perfil.bio,true);checks++;
const diagMissing=calcularDiagnostico(respuestasDiagnosticoDesdeIndices({tam:1,fact:2,sens:0,disp:2,contratos:2,gestion:0}));
assert.ok(diagMissing.faltantes.includes('dpd'));checks++;
// Import integrity for all three catalogs and original boundary values
assert.equal(parametrosMultas.RATES.grave[1],.010);checks++;
assert.equal(parametrosDelegado.CONFIG.P.delegadoMes,95);checks++;
assert.equal(parametrosDiagnostico.QUESTIONS.length,7);checks++;
console.log(`PASS: ${checks} verificaciones de cálculo puro, validación de entradas y repetibilidad.`);
